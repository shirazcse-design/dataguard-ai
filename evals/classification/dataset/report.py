"""Generated dataset report and the per-family human review sheet.

Every number in the report is read from the manifest produced by the generator; nothing is typed
by hand.
"""

from __future__ import annotations

import csv
import io
from typing import Any

from .schema import SPLIT_NAMES, TIERS, DatasetDocument


def _table(headers: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def render_report(
    manifest: dict[str, Any], level_order: list[str], category_order: list[str]
) -> str:
    stats = manifest["stats"]
    by = stats["by_split"]
    integ = manifest["integrity"]
    lines: list[str] = []
    add = lines.append

    add("# UC4 synthetic dataset report")
    add("")
    add("> Generated by `dataguard-uc4 dataset report` from `data/synthetic/uc4/manifest.json`.")
    add("> Do not edit by hand; regenerate after any spec change.")
    add("")
    add("## Identity")
    add("")
    m = manifest
    add(f"* dataset: `{m['dataset_id']}` v{m['dataset_version']}")
    add(f"* generator: `{m['generator_name']}` v{m['generator_version']}, seed `{m['seed']}`")
    add(f"* taxonomy: v{m['taxonomy_version']}; high-risk config: v{m['high_risk_version']}")
    add(f"* dataset sha256: `{m['dataset_sha256']}`")
    n_fam = stats["overall"]["n_families"]
    add(f"* documents: **{m['n_documents']}** in **{n_fam}** scenario families")
    add(f"* **label status: {m['label_status']}**")
    add(f"* per-document annotation status: {m['annotation_status']}")
    add("* the gold labels are NOT independently human-validated")
    add("")
    add("## Splits")
    add("")
    add(
        _table(
            [
                "split",
                "documents",
                "families",
                "high-risk docs",
                "ambiguous docs",
                "docs with no category",
            ],
            [
                [
                    s,
                    by[s]["n_docs"],
                    by[s]["n_families"],
                    by[s]["high_risk_docs"],
                    by[s]["ambiguous_docs"],
                    by[s]["docs_with_no_category"],
                ]
                for s in SPLIT_NAMES
            ],
        )
    )
    add("")
    add("Splitting is by scenario family: every document of a family is in exactly one split.")
    add("")
    add("## Tiers")
    add("")
    add(_table(["split", *TIERS], [[s, *[by[s]["tiers"][t] for t in TIERS]] for s in SPLIT_NAMES]))
    add("")
    add("## Sensitivity levels")
    add("")
    add(
        _table(
            ["split", *level_order],
            [[s, *[by[s]["levels"][lv] for lv in level_order]] for s in SPLIT_NAMES],
        )
    )
    add("")
    add("## Data categories (documents carrying the category)")
    add("")
    add(
        _table(
            ["split", *category_order],
            [[s, *[by[s]["categories"][c] for c in category_order]] for s in SPLIT_NAMES],
        )
    )
    add("")
    add("## Formats")
    add("")
    add(_table(["format", "documents"], [[k, v] for k, v in stats["formats"].items()]))
    add("")
    add("## Integrity and leakage checks")
    add("")
    st = integ["stats"]
    verdict = "PASS" if integ["ok"] else "FAIL"
    n_err, n_warn = len(integ["errors"]), len(integ["warnings"])
    add(f"* result: **{verdict}** ({n_err} errors, {n_warn} warnings)")
    add(f"* cross-split document pairs compared: {st['cross_split_pairs_checked']:,}")
    add(
        "* max cross-split near-duplicate similarity (word 5-gram Jaccard): "
        f"{st['cross_split_max_jaccard']} (fail threshold {st['near_duplicate_threshold']})"
    )
    add(f"* evidence values shared across splits: {st['cross_split_shared_evidence_values']}")
    add(
        f"* within-family similarity: mean {st['within_family_mean_jaccard']}, "
        f"max {st['within_family_max_jaccard']} (informational: documents in a family are "
        "variations of one template, so the effective sample size is the number of families, "
        "not documents)"
    )
    add("")
    add("## Small-sample flags")
    add("")
    flags = integ["small_sample_flags"]
    if flags:
        add("Labels below the minimum-positives threshold for their split (reported, not fatal):")
        add("")
        add(
            _table(
                ["split", "axis", "label", "positives", "minimum"],
                [
                    [f["split"], f["axis"], f["label"], f["positives"], f["min_required"]]
                    for f in flags
                ],
            )
        )
    else:
        add("None.")
    add("")
    return "\n".join(lines) + "\n"


REVIEW_COLUMNS = [
    "family_id", "tier", "split", "n_docs_in_family", "filename", "existing_labels", "gold_level",
    "gold_categories", "ambiguity_flag", "acceptable_alternative_levels", "decoy_for",
    "adversarial_type", "annotation_notes", "content",
    "reviewer_level", "reviewer_categories", "reviewer_agrees (Y/N)", "reviewer_comment",
]  # fmt: skip


def render_review_sheet(docs: list[DatasetDocument]) -> str:
    """One representative document per family (the lowest doc_id), as a CSV for human review.

    All documents of a family share the same gold labels, so confirming one rendered document
    confirms the family's labeling.
    """
    by_family: dict[str, list[DatasetDocument]] = {}
    for d in docs:
        by_family.setdefault(d.family_id, []).append(d)
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerow(REVIEW_COLUMNS)
    for fid in sorted(by_family):
        members = sorted(by_family[fid], key=lambda d: d.doc_id)
        d = members[0]
        writer.writerow(
            [
                fid, d.tier, d.split, len(members), d.filename,
                ";".join(f"{lab.scheme}={lab.value}" for lab in d.existing_labels),
                d.gold_level, ";".join(d.gold_categories), d.ambiguity_flag,
                ";".join(d.acceptable_alternative_levels), ";".join(d.decoy_for),
                d.adversarial_type or "", d.annotation_notes, d.content, "", "", "", "",
            ]
        )  # fmt: skip
    return buf.getvalue()
