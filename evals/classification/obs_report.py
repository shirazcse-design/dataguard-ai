"""Generate the observability and failure-hardening results document.

Nothing is typed by hand: derived metrics come from spans of a real dev run (replayed LLM
responses, no provider call), the privacy audit scans that span output (with a negative control that
proves the audit can fail), and the failure matrix is built from an ACTUAL run of
`tests/failure_injection`. Development splits only; the locked test split is never read.
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path
from typing import Any

from app.classification.hybrid import build_hybrid_classifier
from observability import (
    MemorySink,
    TracedClassifier,
    audit_spans,
    build_tracer,
    load_observability_config,
    summarize,
)

from .dataset.schema import DatasetDocument
from .failure_matrix import ROWS
from .reporting import _f, _table

REPO_ROOT = Path(__file__).resolve().parents[2]


def _ms(v: float | None) -> str:
    """Stable display: local stages are sub-millisecond; recorded model stages are shown in s."""
    if v is None:
        return "n/a"
    if v < 1:
        return "<1 ms"
    if v < 1000:
        return f"{v:.0f} ms"
    return f"{v / 1000:.1f} s"


def run_failure_suite(repo_root: Path = REPO_ROOT) -> dict[str, Any]:
    """Run tests/failure_injection and return {row_id: [(test name, outcome)]} plus totals."""
    suite = repo_root / "tests" / "failure_injection"
    if not suite.exists():
        return {"available": False}
    with tempfile.TemporaryDirectory() as tmp:
        xml_path = Path(tmp) / "junit.xml"
        proc = subprocess.run(
            [sys.executable, "-m", "pytest", str(suite), "-q", "-p", "no:cacheprovider",
             f"--junitxml={xml_path}"],
            cwd=repo_root, capture_output=True, text=True,
        )  # fmt: skip
        if not xml_path.exists():
            return {"available": False, "error": proc.stdout[-300:]}
        root = ET.parse(xml_path).getroot()
    rows: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for tc in root.iter("testcase"):
        name = tc.get("name", "")
        if not name.startswith("test_row_"):
            continue
        rid = name.split("_")[2]
        outcome = (
            "failed"
            if tc.find("failure") is not None or tc.find("error") is not None
            else ("skipped" if tc.find("skipped") is not None else "passed")
        )
        rows[rid].append((name, outcome))
    return {"available": True, "rows": dict(rows), "exit_code": proc.returncode}


def build_obs_report(
    bundle,
    dev: list[DatasetDocument],
    git: dict[str, Any],
    *,
    failure_suite: dict[str, Any] | None = None,
) -> str:
    cfg, cfg_sha = load_observability_config()
    sink = MemorySink()
    tracer, salt = build_tracer(cfg, [sink], deterministic_ids=True)
    clf = TracedClassifier(build_hybrid_classifier(bundle, variant="default"), tracer, salt)
    for d in sorted(dev, key=lambda x: x.doc_id):
        clf.classify(d.to_request())
    spans = sink.spans
    text = "\n".join(s.model_dump_json() for s in spans)
    m = summarize(spans)
    audit = audit_spans(text, dev)
    control = audit_spans(
        text + '\n{"attributes": {"x": "' + dev[0].content[:120].replace('"', "'") + '"}}',
        dev,
    )
    suite = failure_suite if failure_suite is not None else run_failure_suite()

    L: list[str] = []
    add = L.append
    add("# Observability and failure-hardening results (Phase 7)")
    add("")
    add(
        "> Generated by `dataguard-uc4 obs report` from executed code on the DEVELOPMENT split. LLM "
        "responses are replayed from the recorded benchmark; no provider call was made. **The locked "
        "test split was not read.** Dataset labels: **AI-generated synthetic dataset — pending human "
        "gold-label review**."
    )
    add("")
    add(
        "> **Export to Azure Monitor / Foundry tracing is NOT verified**: no Application Insights connection string exists here. Spans are exported to JSONL, memory and (optionally) the OpenTelemetry SDK, which is tested with its in-memory exporter."
    )
    add("")
    add("## Protocol")
    add("")
    add(
        "* pre-registered plan: `docs/uc4/observability-plan.md` (committed before any Phase 7 code)"
    )
    add(
        f"* observability config `{cfg.observability_version}` sha256 `{cfg_sha[:16]}...`; {len(cfg.allowed_attributes)} allow-listed attribute keys (deny by default)"
    )
    add(
        f"* traced run: hybrid `default` over {len(dev)} dev documents -> {m['n_traces']} traces, {m['n_spans']} spans"
    )
    add(
        f"* git `{(git.get('commit') or 'unknown')[:12]}` on `{git.get('branch')}` (dirty: {git.get('dirty')})"
    )
    add("")

    add("## Derived metrics (from spans)")
    add("")
    add(
        _table(
            ["stage span", "spans", "errors", "P50", "P95"],
            [
                [n, v["n"], v["errors"], _ms(v["p50_ms"]), _ms(v["p95_ms"])]
                for n, v in m["stage_latency"].items()
            ],
        )
    )
    add("")
    add(
        "LLM stage latency is the RECORDED latency of the benchmark; local stages are measured wall-clock and shown as `<1 ms` when sub-millisecond."
    )
    add("")
    add(_table(["measure", "value"], [
        ["route distribution", m["route_distribution"]],
        ["status distribution", m["status_distribution"]],
        ["review rate", _f(m["review_rate"])],
        ["LLM calls per trace", _f(m["llm_calls_per_trace"], 2)],
        ["tokens per trace", _f(m["tokens_per_trace"], 0)],
        ["estimated cost per trace", "not estimated (no price configured)" if m["est_cost_usd_per_trace"] is None else _f(m["est_cost_usd_per_trace"], 4)],
        ["schema-validation failure rate", _f(m["schema_failure_rate"])],
        ["evidence-verification failure rate", _f(m["evidence_verification_failure_rate"])],
        ["fallbacks (escalations / degraded / failed stage spans / retries)", " / ".join(str(m["fallbacks"][k]) for k in ("escalations", "degraded_results", "failed_stage_spans", "retries"))],
        ["guardrail triggers", m["guardrail_triggers"] or "none"],
        ["attributes dropped by the redactor", m["dropped_attributes"]],
    ]))  # fmt: skip
    add("")
    add(
        "With the recorded model outputs nothing fails, escalates or retries on dev; those counters are exercised by the failure-injection suite below."
    )
    add("")

    add("## Privacy audit")
    add("")
    add(_table(["check", "result"], [
        ["documents scanned", audit.documents],
        ["6-word content windows checked against all span output", audit.windows_checked],
        ["gold evidence spans checked", audit.evidence_spans_checked],
        ["filenames checked", audit.filenames_checked],
        ["sensitive-value patterns checked", audit.pattern_checks],
        ["**leaks found**", f"**{len(audit.leaks)}**" + (f" {audit.leaks[:5]}" if audit.leaks else "")],
        ["negative control: an injected document sentence is detected", "yes" if not control.clean else "**NO: the audit cannot fail**"],
    ]))  # fmt: skip
    add("")
    add(
        "The audit reads every key and string value of the exported spans (numbers such as timestamps and hex ids are excluded). `dataguard-uc4 obs audit` is a CI gate."
    )
    add("")

    add(
        "## Failure matrix (architecture section 19), from an actual run of `tests/failure_injection`"
    )
    add("")
    if not suite.get("available"):
        add(
            "The failure-injection suite was not available in this environment; the matrix is therefore **not evaluated** here."
        )
    else:
        rows = suite["rows"]
        table = []
        total_p = total_f = 0
        for rid, desc in ROWS.items():
            tests = rows.get(rid, [])
            passed = sum(o == "passed" for _, o in tests)
            failed = sum(o == "failed" for _, o in tests)
            total_p += passed
            total_f += failed
            table.append(
                [
                    rid,
                    desc,
                    len(tests),
                    passed,
                    failed,
                    "PASS" if tests and not failed else "**FAIL**",
                ]
            )
        add(_table(["row", "failure", "tests", "passed", "failed", "result"], table))
        add("")
        add(
            f"{total_p} tests passed, {total_f} failed (pytest exit code {suite['exit_code']}). Every row has at least one end-to-end test through the real classifiers, a local fake provider server, or injected faults."
        )
    add("")
    add("## Caveats")
    add("")
    for c in (
        "Spans are not verified against Azure Monitor or Foundry tracing (no connection string).",
        "The fake provider server verifies the adapter's failure handling, not the real service's; real failure rates and latencies are unmeasured.",
        "The privacy audit proves the absence of the tested strings and patterns, not the absence of every conceivable leak; the allow-list and redactor are the primary control.",
        "An offline static dashboard exists (`dataguard-uc4 obs dashboard`); a shared, live dashboard (DG-018) is not built.",
        "Synthetic, AI-authored labels not yet human reviewed; nothing transfers to real data without validation.",
    ):
        add(f"* {c}")
    add("")
    return "\n".join(L)
