"""Generate the Rules Engine baseline results document from executed runs.

Every number is computed here from the classifier's actual outputs on the DEVELOPMENT splits
(train, calibration, dev). The locked test split is never read.
"""

from __future__ import annotations

from typing import Any

from app.classification.config_loader import ConfigBundle
from rules.classifier import RulesClassifier

from .dataset.schema import DatasetDocument
from .evaluate import EvaluationResult, evaluate
from .reporting import _ci, _f, _flag, _table
from .rules_analysis import analyze, render

SPLITS = ("train", "calibration", "dev")
PRE_CHECK_BUDGET_MS = 500  # PRD section 5.1: deterministic pre-check <= 500 ms


def _signal_stats(clf: RulesClassifier, docs: list[DatasetDocument]) -> dict[str, Any]:
    """How much of the corpus the rules reach at all (decisive / weak-only / no signal)."""
    decisive = weak_only = no_signal = 0
    per_tier: dict[str, dict[str, int]] = {}
    for d in docs:
        res = clf.engine.analyze(d.to_request().document)
        kind = (
            "decisive"
            if res.level is not None
            else ("weak_only" if res.detections else "no_signal")
        )
        decisive += kind == "decisive"
        weak_only += kind == "weak_only"
        no_signal += kind == "no_signal"
        t = per_tier.setdefault(d.tier, {"decisive": 0, "weak_only": 0, "no_signal": 0, "n": 0})
        t[kind] += 1
        t["n"] += 1
    n = len(docs)
    return {
        "n": n,
        "decisive": decisive,
        "weak_only": weak_only,
        "no_signal": no_signal,
        "coverage": decisive / n if n else None,
        "per_tier": per_tier,
    }


def _summary_row(name: str, res: EvaluationResult) -> list[Any]:
    h = res.metrics["headline"]
    hm, st = h["metrics"], h["confidence_intervals"]["statistics"]
    hr, cov = hm["high_risk"], res.metrics["all_tiers"]["coverage"]
    lat = res.metrics["latency"]["wall_clock"]
    return [
        name,
        f"{hm['coverage']['n_docs']} / {hm['coverage']['n_groups']}",
        _ci(st["level_macro_f1"]),
        _ci(st["category_macro_f1"]),
        _f(hr["precision"]),
        _ci(st["high_risk_recall"]),
        _f(hr["f1"]),
        _f(hr["false_positive_rate"]),
        f"{cov['n_abstained']}/{cov['n_docs']} ({_f(cov['abstention_rate'])})",
        f"{lat['p50_ms']:.2f} / {lat['p95_ms']:.2f}",
    ]


def build_rules_report(
    bundle: ConfigBundle,
    clf: RulesClassifier,
    docs_by_split: dict[str, list[DatasetDocument]],
    dataset_manifest: dict[str, Any],
    git: dict[str, Any],
) -> str:
    policy = bundle.policy
    threshold = bundle.eval.min_support_flag
    results = {s: evaluate(clf, docs_by_split[s], bundle, dataset_manifest) for s in SPLITS}
    pooled_docs = [d for s in SPLITS for d in docs_by_split[s]]
    pooled = evaluate(clf, pooled_docs, bundle, dataset_manifest)
    ph = pooled.metrics["headline"]
    hm = ph["metrics"]
    stats = ph["confidence_intervals"]["statistics"]
    man = pooled.manifest
    L: list[str] = []
    add = L.append

    add("# Rules Engine baseline results (ruleset " + clf.version + ")")
    add("")
    add(
        "> Generated by `dataguard-uc4 rules report` from executed runs. Every number is computed from "
        "the engine's actual outputs on the DEVELOPMENT splits; nothing is typed by hand. "
        "**The locked test split was not read.**"
    )
    add("")
    add("## Provenance and protocol")
    add("")
    add(
        f"* **dataset labels: {man['dataset']['label_status']}** (not independently human-validated)"
    )
    add(
        f"* ruleset `{clf.version}`, standalone default level `{clf.params()['standalone_default_level']}`"
    )
    add(f"* rules config sha256 `{clf.params()['rules_config_sha256'][:16]}...`")
    add(f"* dataset sha256 `{man['dataset']['dataset_sha256'][:16]}...`")
    add(
        f"* git `{(git.get('commit') or 'unknown')[:12]}` on `{git.get('branch')}` (dirty: {git.get('dirty')})"
    )
    add(
        "* development protocol: errors inspected on **train**; **dev** evaluated at checkpoints; "
        "**calibration** untouched until this report; every post-first-run change is in "
        "`docs/uc4/rules-changelog.md`. The rules were written by the same assistant that authored "
        "the dataset, and the train figures were used to tune three details, so **train and pooled "
        "numbers are development-contaminated**."
    )
    add("* the purpose is an honest deterministic baseline, not to beat ML or an LLM.")
    add("")
    add(
        "**No rule match does not mean Public.** Where rules find no decisive level evidence they "
        "abstain; for this standalone benchmark only, an abstained level is scored as the configurable "
        "default `INTERNAL`. Rules never output `PUBLIC`."
    )
    add("")

    add("## Summary by split (headline tiers T1-T4; documents / families)")
    add("")
    add(
        _table(
            ["split", "docs / families", "level macro-F1", "category macro-F1", "HR precision",
             "HR recall", "HR F1", "HR FPR", "abstained", "latency p50 / p95 ms"],
            [_summary_row(s, results[s]) for s in SPLITS] + [_summary_row("pooled development", pooled)],
        )
    )  # fmt: skip
    add("")
    n_units = ph["confidence_intervals"]["n_units"]
    add(
        f"Intervals are family-level percentile bootstrap intervals (95%); the pooled row rests on "
        f"**{n_units} independent families**, the per-split rows on far fewer (see the families column). "
        "HR = high-risk. Read recall together with precision and FPR; no operating point has been chosen."
    )
    add("")
    add(f"### Sample-size warnings by split (SMALL_SAMPLE: fewer than {threshold} gold positives)")
    add("")
    rows = []
    for name, res in [*((s, results[s]) for s in SPLITS), ("pooled development", pooled)]:
        sm = res.metrics["headline"]["small_sample_labels"]
        flagged = {**sm["levels"], **sm["categories"]}
        counts = res.metrics["headline"]["metrics"]
        supports = {
            **{k: v["support"] for k, v in counts["level"]["per_class"].items()},
            **{k: v["support"] for k, v in counts["categories"]["per_label"].items()},
        }
        rows.append(
            [
                name,
                ", ".join(f"{k} (n={v})" for k, v in flagged.items()) or "none",
                f"min {min(supports.values())}, max {max(supports.values())}",
            ]
        )
    add(
        _table(["split", "SMALL_SAMPLE labels (headline subset)", "per-label gold positives"], rows)
    )
    add("")
    add(
        "Per-label counts for the pooled set are in the `support` columns below. No examples were added to reach a count."
    )
    add("")
    ref = bundle.eval.reference_targets.get("high_risk_recall")
    if ref is not None:
        got = stats["high_risk_recall"]["point"]
        add(
            f"Initial high-risk recall reference {ref:.2f} (informational, not a gate): pooled observed "
            f"{_f(got)}, i.e. **{'at or above' if got >= ref else 'below'} the reference**."
        )
        add("")

    add("## Pooled development set: detail")
    add("")
    add(
        f"Headline tiers {', '.join(ph['tiers'])}: {hm['coverage']['n_docs']} documents, {hm['coverage']['n_groups']} families."
    )
    add("")
    add("### Sensitivity level")
    add("")
    lv = hm["level"]
    cm = lv["confusion_matrix"]
    add(
        "Confusion matrix (rows = gold, columns = predicted; abstentions appear as the default level):"
    )
    add("")
    add(
        _table(
            ["gold \\ predicted", *cm["cols_predicted"]],
            [[g, *r] for g, r in zip(cm["rows_gold"], cm["values"], strict=True)],
        )
    )
    add("")
    add(
        _table(
            ["level", "precision", "recall", "F1", "support", "predicted", "warning"],
            [
                [
                    k,
                    v["precision"],
                    v["recall"],
                    v["f1"],
                    v["support"],
                    v["predicted"],
                    _flag(v["support"], threshold),
                ]
                for k, v in lv["per_class"].items()
            ],
        )
    )
    add("")
    o = lv["ordinal_errors"]
    add(
        f"macro P/R/F1 {_f(lv['macro']['precision'])} / {_f(lv['macro']['recall'])} / {_f(lv['macro']['f1'])} "
        f"(interval {_ci(stats['level_macro_f1'])}); micro F1 {_f(lv['micro']['f1'])}; accuracy {_f(lv['accuracy'])}. "
        f"**Under-classification rate {_f(o['under_classification_rate'])}** "
        f"(severe {_f(o['severe_under_classification_rate'])}); over-classification {_f(o['over_classification_rate'])}."
    )
    add("")
    add("### Data categories (per-category performance)")
    add("")
    cat = hm["categories"]
    add(
        _table(
            ["category", "precision", "recall", "F1", "support", "TP", "FP", "FN", "warning"],
            [
                [
                    k,
                    v["precision"],
                    v["recall"],
                    v["f1"],
                    v["support"],
                    v["tp"],
                    v["fp"],
                    v["fn"],
                    _flag(v["support"], threshold),
                ]
                for k, v in cat["per_label"].items()
            ],
        )
    )
    add("")
    add(
        f"macro P/R/F1 {_f(cat['macro']['precision'])} / {_f(cat['macro']['recall'])} / {_f(cat['macro']['f1'])} "
        f"(interval {_ci(stats['category_macro_f1'])}); micro P/R/F1 {_f(cat['micro']['precision'])} / "
        f"{_f(cat['micro']['recall'])} / {_f(cat['micro']['f1'])}; exact-match {_f(cat['exact_match_ratio'])}."
    )
    add("")
    add("### High-risk (derived from the configured definition)")
    add("")
    hr = hm["high_risk"]
    add(
        _table(
            ["TP", "FP", "FN", "TN", "precision", "recall", "F1", "FPR", "prevalence"],
            [
                [
                    hr["tp"],
                    hr["fp"],
                    hr["fn"],
                    hr["tn"],
                    hr["precision"],
                    hr["recall"],
                    hr["f1"],
                    hr["false_positive_rate"],
                    hr["prevalence"],
                ]
            ],
        )
    )
    add("")
    add(
        f"precision {_ci(stats['high_risk_precision'])}; recall {_ci(stats['high_risk_recall'])}; "
        f"F1 {_ci(stats['high_risk_f1'])}; FPR {_ci(stats['high_risk_false_positive_rate'])}."
    )
    add("")

    sig = _signal_stats(clf, pooled_docs)
    cov = pooled.metrics["all_tiers"]["coverage"]
    add("## Abstention and rules coverage (all tiers, pooled)")
    add("")
    add(
        f"* documents: {sig['n']}; **abstention rate {_f(cov['abstention_rate'])}** "
        f"({cov['n_abstained']} documents where rules produced no decisive level evidence)"
    )
    add(
        f"* **rules coverage {_f(sig['coverage'])}**: documents with decisive (strong/definitive) evidence: {sig['decisive']}"
    )
    add(
        f"* weak signals only (retained but asserting nothing): {sig['weak_only']}; no signal at all: {sig['no_signal']}"
    )
    add("")
    add(
        _table(
            ["tier", "documents", "decisive", "weak only", "no signal", "coverage"],
            [
                [
                    t,
                    v["n"],
                    v["decisive"],
                    v["weak_only"],
                    v["no_signal"],
                    _f(v["decisive"] / v["n"]),
                ]
                for t, v in sorted(sig["per_tier"].items())
            ],
        )
    )
    add("")

    lat = pooled.metrics["latency"]
    wall, inner = lat["wall_clock"], lat["classifier_reported"]
    add("## Latency (measured; PRD pre-check target <= 500 ms)")
    add("")
    add(
        _table(
            ["measure", "n", "mean ms", "p50 ms", "p95 ms", "max ms"],
            [
                [
                    "harness wall clock per document",
                    wall["n"],
                    wall["mean_ms"],
                    wall["p50_ms"],
                    wall["p95_ms"],
                    wall["max_ms"],
                ],
                [
                    "engine-internal (classifier-reported)",
                    inner["n"],
                    inner["mean_ms"],
                    inner["p50_ms"],
                    inner["p95_ms"],
                    inner["max_ms"],
                ],
            ],
        )
    )
    add("")
    verdict = (
        "within"
        if wall["p95_ms"] <= PRE_CHECK_BUDGET_MS and wall["max_ms"] <= PRE_CHECK_BUDGET_MS
        else "OUTSIDE"
    )
    add(
        f"Measured p95 {wall['p95_ms']:.3f} ms and max {wall['max_ms']:.3f} ms across {wall['n']} documents: "
        f"**{verdict}** the {PRE_CHECK_BUDGET_MS} ms budget. Documents here are at most a few KB; "
        "adversarial 200 KB inputs are covered by unit tests (worst measured 213 ms after the scan cap)."
    )
    add("")

    add("## Performance by difficulty tier (all tiers, pooled)")
    add("")
    tiers = pooled.metrics["slices"]["tier"]
    add(
        _table(
            [
                "tier",
                "docs",
                "families",
                "level macro-F1",
                "category macro-F1",
                "HR recall",
                "HR precision",
                "HR FPR",
                "warning",
            ],
            [
                [
                    t,
                    v["n_docs"],
                    v["n_groups"],
                    v["level_macro_f1"],
                    v["category_macro_f1"],
                    v["high_risk_recall"],
                    v["high_risk_precision"],
                    v["high_risk_false_positive_rate"],
                    "SMALL_SAMPLE" if v["small_sample"] else "",
                ]
                for t, v in tiers.items()
            ],
        )
    )
    add("")
    add(
        "T1 easy, T2 semantic, T3 ambiguous, T4 hard negative, T5 adversarial. T5 is excluded from the headline and shown here."
    )
    add("")

    hn = pooled.metrics["hard_negatives"]
    add("## Hard negatives (T4)")
    add("")
    add(
        f"{hn['n_docs']} documents / {hn['n_families']} families. **Hard-negative false-positive (decoy-hit) rate "
        f"{_f(hn['decoy_hit_rate'])}**; any false-positive category {_f(hn['any_false_positive_category_rate'])}; "
        f"predicted high-risk though not {_f(hn['high_risk_false_positive_rate'])}."
    )
    add("")
    add(f"Families with decoy hits: `{hn['families_with_decoy_hits'] or 'none'}`")
    add("")

    add("## Error analysis (pooled development set; all tiers)")
    add("")
    add(
        render(
            analyze(clf, pooled_docs, policy),
            "Families where rules err, with the detector responsible",
        ).split("\n", 2)[2]
    )
    return "\n".join(L) + "\n"
