"""Golden examples for the frozen schema: one real request/result pair per status.

Generated by running the real service (rules-only, replayed LLM responses, injected faults); nothing
is typed by hand. Telemetry latencies are normalised to a constant so the files are reproducible.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any
from unittest import mock

from app.classification.boundary import classify_safely
from app.classification.service import ClassificationService
from evals.classification.dataset.build import DEFAULT_DATA_DIR, load_documents

RECORD = (
    "Employee record\nNational ID: 905-37-6209\nDate of birth: 01/27/1960\n"
    "Reports to Tariq Alvarez in Marketing.\n"
)
UNSEEN = "Notes from the supplier call: pricing tiers for the next contract round are attached."


def _normalise(result: dict[str, Any]) -> dict[str, Any]:
    tel = result.get("telemetry", {})
    tel["latency_ms"] = {k: 1.0 for k in tel.get("latency_ms", {})}
    return result


def _dump(request: dict[str, Any], result) -> dict[str, Any]:
    return {"request": request, "result": _normalise(result.model_dump(mode="json"))}


def _request(
    rid: str,
    content: str,
    filename: str = "employee_record.txt",
    extension: str = "txt",
    **options: Any,
) -> dict[str, Any]:
    body: dict[str, Any] = {
        "schema_version": "1.0",
        "request_id": rid,
        "document": {"content": content, "filename": filename, "extension": extension},
    }
    if options:
        body["options"] = options
    return body


def build_examples(config_dir=None, data_dir=None) -> dict[str, dict[str, Any]]:
    off = ClassificationService(llm_mode="off", config_dir=config_dir, data_dir=data_dir)
    replay = ClassificationService(llm_mode="replay", config_dir=config_dir, data_dir=data_dir)
    out: dict[str, dict[str, Any]] = {}

    def meta(name: str, description: str, pair: dict[str, Any]) -> None:
        out[name] = {"description": description, **pair}

    # ok: Rules decide (deterministic, no model)
    req = _request("example-ok-rules", RECORD, mode="rules")
    meta(
        "ok-rules",
        "Rules-only request on a record with a national ID: status ok, high-risk.",
        _dump(req, off.classify(req)),
    )

    # a dev document with a recorded LLM response (the replay key includes the filename)
    docs = sorted(
        load_documents(data_dir or DEFAULT_DATA_DIR, splits=["dev"]), key=lambda d: d.doc_id
    )
    target = None
    for doc in docs:
        if doc.tier != "T2":
            continue
        req = _request("example-ok-hybrid", doc.content, doc.filename, doc.extension)
        res = replay.classify(req)
        if res.status == "ok" and any(e.type == "llm_excerpt" and e.verified for e in res.evidence):
            target = (doc, req, res)
            break
    if target is None:
        raise RuntimeError("no dev document gives a verified hybrid example")
    doc, req, res = target
    meta(
        "ok-hybrid",
        "Default hybrid: Rules abstain, the mid LLM tier decides; verified evidence.",
        _dump(req, res),
    )

    # degraded: a Rules detector fails while the LLM still decides
    req = _request("example-degraded", doc.content, doc.filename, doc.extension)
    engine = replay._classifier._rules.engine  # noqa: SLF001 - fault injection for the example only
    with mock.patch.object(
        engine.detectors[0], "detect", side_effect=RuntimeError("detector fault")
    ):
        res = replay.classify(req)
    meta(
        "degraded",
        "A configured stage (a Rules detector) failed but another stage decided: degraded.",
        _dump(req, res),
    )

    # review_required: no recorded/live LLM answer and Rules abstain -> no label, review
    req = _request("example-review-required", UNSEEN, mode="llm")
    meta(
        "review-required",
        "The LLM stage is unavailable and Rules cannot decide: review, no label.",
        _dump(req, replay.classify(req)),
    )

    # rejected: unusable input
    req = _request("example-rejected", "   \n")
    meta(
        "rejected",
        "Whitespace-only text: rejected with a reason; no level, no text in the result.",
        _dump(req, off.classify(req)),
    )

    # error: an unexpected failure inside a classifier
    class Boom:
        name, version = "boom", "0"

        def classify(self, request):
            raise RuntimeError("unexpected failure")

        def params(self):
            return {}

    req = _request("example-error", RECORD)
    res = classify_safely(Boom(), req, guard=off._guard)  # noqa: SLF001
    meta(
        "error",
        "An unexpected failure in a classifier: an error result, never a low sensitivity.",
        _dump(req, res),
    )
    return out


def write_examples(out_dir: Path, config_dir=None, data_dir=None) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, body in build_examples(config_dir, data_dir).items():
        p = out_dir / f"{name}.json"
        p.write_text(json.dumps(body, indent=2) + "\n", encoding="utf-8")
        paths.append(p)
    return paths
