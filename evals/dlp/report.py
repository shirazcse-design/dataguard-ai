"""Writes docs/uc1/results/eval.{json,md}: the UC1 golden-set evaluation, with provenance."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[2]
RESULTS = REPO / "docs" / "uc1" / "results"

LABELS = {
    "outcome_accuracy": "Outcome accuracy (exact expected outcome)",
    "acceptable_outcome_accuracy": "Outcome accuracy (any acceptable outcome)",
    "high_risk_recall": "High-risk recall (expected ESCALATE/HUMAN_REVIEW, returned one of them)",
    "critical_false_negative_count": "critical_false_negative_count (high-risk case returned ALLOW)",
    "false_positive_rate": "False-positive rate (expected ALLOW, returned anything else)",
    "hitl_precision": "HITL precision (HUMAN_REVIEW returned where it was expected/acceptable)",
    "hitl_recall": "HITL recall (expected HUMAN_REVIEW, returned HUMAN_REVIEW)",
    "agent_task_completion": "Agent task completion (final answer)",
    "required_tool_use": "Agent required-tool use (exception check where required)",
    "tool_argument_validity": "Tool-argument validity",
    "unnecessary_calls_per_case": "Unnecessary tool calls per case (repeats + failed)",
    "budget_compliance": "Step-budget compliance",
    "safe_termination": "Safe termination (stopped early -> never ALLOW)",
    "agent_proposal_agreement": "Agent proposal within acceptable outcomes",
    "policy_selection_correctness": "Policy selection (expected section among VERIFIED UC6 citations)",
    "unsupported_finding_rate": "Unsupported agent findings (citing no known evidence id)",
    "insufficient_evidence_behaviour": "Missing policy evidence on high-risk case -> HUMAN_REVIEW",
    "unauthorized_tool_attempts": "Unauthorized tool attempts (unlisted tools)",
    "tool_boundary_violations": "Tool-boundary violations (unlisted + invalid arguments)",
    "injection_resistance": "Prompt-injection resistance (adversarial cases acceptable)",
    "critical_safety_violations": "Critical safety violations (critical false negatives; no real action exists)",
}


def _fmt(v: Any) -> str:
    if v is None:
        return "-"
    return f"{v:.3f}" if isinstance(v, float) else str(v)


def render(report: dict[str, Any]) -> str:
    p, s = report["provenance"], report["summary"]
    lines = [
        "# UC1 Agentic DLP evaluation (generated)",
        "",
        "Generated by `dataguard-dlp eval`. Do not edit by hand.",
        "",
        f"* Mode: **{p['mode'].upper()}**; agent backend `{p['agent_backend']}`; planner `{p['planner']}`",
        f"* Golden set: {p['cases']} cases, sha256 `{p['golden_sha256'][:12]}`; rubric `{p['rubric_version']}`, mapping `{p['mapping_version']}`; "
        f"config hashes {', '.join(f'`{k}` {v[:8]}' for k, v in p['config_hashes'].items())}",
        "* Faults marked SIMULATED in a case are injected test failures, not real outages.",
    ]
    if p["mode"] == "offline":
        lines.append(
            "* **OFFLINE: the agent is the deterministic `offline-planner` and UC6 uses its extractive stand-in; these numbers exercise the harness, they are not model results.**"
        )
    lines += ["", "## Metrics", "", "| Metric | Kind | Value | n |", "|---|---|---|---|"]
    for k, m in s["metrics"].items():
        lines.append(f"| {LABELS[k]} | {m['kind']} | {_fmt(m['value'])} | {m['n']} |")
    lines += ["", f"Outcomes: {s['outcomes']}", "", "## System (local run)", ""]
    for k, v in s["system"].items():
        lines.append(f"* {k}: {v}")
    lines += [
        "",
        "## Per case",
        "",
        "| Case | Category | Expected | Outcome | Score | Policy | Agent | Notes |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in report["cases"]:
        note = []
        if not r["ok"]:
            note.append("**MISS**")
        if r["critical_false_negative"]:
            note.append("**CRITICAL FN**")
        if r["false_positive"]:
            note.append("false positive")
        if r["simulated_faults"]:
            note.append("SIMULATED " + ",".join(r["simulated_faults"]))
        if r["injection"]:
            note.append("injection flagged")
        lines.append(
            f"| {r['id']} | {r['category']} | {r['expected']} | {r['outcome']} | {r['score']} | {r['policy_status']}/{r['policy_effect']} | {r['agent_proposal'] or '-'} ({r['agent_stopped']}) | {'; '.join(note)} |"
        )
    return "\n".join(lines) + "\n"


def write(report: dict[str, Any], stem: str = "eval") -> Path:
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / f"{stem}.json").write_text(
        json.dumps(report, indent=1, sort_keys=True, default=str) + "\n", encoding="utf-8"
    )
    md = RESULTS / f"{stem}.md"
    md.write_text(render(report), encoding="utf-8")
    return md
