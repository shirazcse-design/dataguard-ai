"""UC5 observability evidence (`dataguard-incident obs report`): the 16 golden incidents through the
PRODUCTION tracer and redactor, a privacy audit of every exported span, and a telemetry summary.

The audit checks that no span carries: a raw user id, an agent-facing alias, untrusted free text
(log comments, user justifications), document text, policy text, destination hosts or file
handles' document ids, or any attribute key outside the dg.* allow-list.
"""

from __future__ import annotations

import json
from collections import Counter
from typing import Any

from observability.config import build_tracer, load_observability_config
from observability.sinks import MemorySink, _genai_attrs


def run_traced(mode: str = "offline") -> dict[str, Any]:
    from app.incident import synth
    from app.incident.services import alias, build_services
    from evals.incident.agent_eval import run

    cfg, _ = load_observability_config()
    sink = MemorySink()
    tracer, _ = build_tracer(cfg, [sink], deterministic_ids=True)
    report = run(mode, tracer=tracer)
    spans = sink.spans
    blob = json.dumps([s.model_dump() for s in spans], default=str)
    incs = synth.INCIDENTS
    svc = build_services("offline" if mode == "offline" else "replay")
    docs = svc.uc2.data_uc4.documents
    needles: dict[str, list[str]] = {
        "user_id": sorted({i["user_id"] for i in incs}),
        "agent_alias": sorted({alias(i["user_id"]) for i in incs}),
        "untrusted_text": sorted({o[k][:40] for i in incs for o in i["overlays"] for k in ("text", "user_justification") if o.get(k)}),
        "document_id": sorted({f["ref"].split(":")[1] for i in incs for f in i["files"]}),
        "document_text": sorted({docs.get(f["ref"]).content[:50] for i in incs for f in i["files"] if len(docs.get(f["ref"]).content) > 50}),
        "destination_host": sorted({o["destination"] for i in incs for o in i["overlays"] if o.get("destination")}),
        "policy_text": sorted({c.body[:60] for c in svc.uc2.copilot.corpus.chunks if len(c.body) > 60}),
    }  # fmt: skip
    leaks = [[k, v[:30]] for k, vs in needles.items() for v in vs if v in blob]
    allowed = set(cfg.allowed_attributes)
    unlisted = sorted({k for s in spans for k in s.attributes if k not in allowed})
    roots = [s for s in spans if s.name == "uc5.incident_case"]
    tools = [s for s in spans if s.name == "uc5.tool"]

    def count(vals):
        return dict(sorted(Counter(v for v in vals if v is not None).items()))

    telemetry = {
        "spans": len(spans), "cases": len(roots), "span_names": count(s.name for s in spans),
        "severity": count(r.attributes.get("dg.ic.severity") for r in roots),
        "review_required": sum(r.attributes.get("dg.ic.review_status") == "REQUIRED" for r in roots),
        "tool_calls": count(s.attributes.get("dg.agent.tool") for s in tools),
        "tool_errors": count(s.attributes["dg.agent.tool_error"] for s in tools if "dg.agent.tool_error" in s.attributes),
        "genai_operations": count(_genai_attrs(s.name, s.attributes).get("gen_ai.operation.name") for s in spans if _genai_attrs(s.name, s.attributes)),
    }  # fmt: skip
    audit = {"clean": not leaks and not unlisted, "spans_audited": len(spans),
             "checks": sum(len(v) for v in needles.values()), "leaks": leaks, "unlisted_keys": unlisted}  # fmt: skip
    return {
        "mode": mode,
        "verification": report["verification"],
        "privacy_audit": audit,
        "telemetry": telemetry,
    }


def render(r: dict[str, Any]) -> str:
    a, t = r["privacy_audit"], r["telemetry"]
    lines = ["# UC5 observability evidence (generated)", "",
             f"Generated by `dataguard-incident obs report` ({r['verification']}) through the PRODUCTION tracer and redactor.", "",
             f"* Privacy audit: **{'CLEAN' if a['clean'] else 'LEAKS FOUND'}**. {a['spans_audited']} spans; {a['checks']} checks for raw user ids, "
             "agent aliases, untrusted free text, document ids and text, destination hosts and policy text; every attribute key on the dg.* allow-list.",
             *([f"* Leaks: {a['leaks']}"] if a["leaks"] else []), *([f"* Unlisted keys: {a['unlisted_keys']}"] if a["unlisted_keys"] else []),
             "", "| Signal | Value |", "|---|---|"]  # fmt: skip
    lines += [f"| {k} | {str(v).replace('|', '/')} |" for k, v in t.items()]
    return "\n".join(lines) + "\n"
