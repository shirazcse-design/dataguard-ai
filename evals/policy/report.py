"""Writes the generated retrieval results (`docs/uc6/results/retrieval.{json,md}`)."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .retrieval_eval import KS

REPO = Path(__file__).resolve().parents[2]
RESULTS_DIR = REPO / "docs" / "uc6" / "results"


def _row(name: str, s: dict[str, Any]) -> str:
    o = s["overall"]
    cells = [f"{o[f'recall@{k}']:.3f}" for k in KS] + [f"{o[f'precision@{k}']:.3f}" for k in KS]
    cells += [f"{o['hit@5']:.3f}", f"{o['mrr']:.3f}", f"{s['draft_in_top_k_rate']:.3f}"]
    cells.append(f"{s['conflict_surfaced_rate']:.3f}" if "conflict_surfaced_rate" in s else "-")
    return f"| {name} | " + " | ".join(cells) + " |"


def render_markdown(report: dict[str, Any]) -> str:
    prov = report["provenance"]
    lines = [
        "# UC6 retrieval evaluation (generated)",
        "",
        "Generated by `dataguard-policy eval retrieval`. Do not edit by hand.",
        "",
        f"* Embedding mode: **{prov['embed_mode'].upper()}** - model id `{prov['embedding_model_id']}`",
    ]
    if prov["embedding_model_id"] == "offline-hash":
        lines.append(
            "* **The dense leg used the OFFLINE hashing embedder, which is NOT a semantic model.** "
            "Dense and hybrid numbers in this file say nothing about real embedding retrieval."
        )
    lines += [
        f"* Golden set: {prov['golden_items']} items ({prov['scored_items']} with expected "
        f"evidence), sha256 `{prov['golden_sha256'][:12]}`",
        f"* Corpus fingerprint `{prov['corpus_fingerprint'][:12]}` - {prov['chunks']} chunks; "
        f"config sha256 `{prov['config_sha256'][:12]}`",
        "* All metrics are **deterministic** (retrieved section keys vs `expected_sections`).",
        "",
        "## Ablation ladder (all scored items)",
        "",
        "| Variant | R@3 | R@5 | R@10 | P@3 | P@5 | P@10 | Hit@5 | MRR | Draft in top-k | Conflict surfaced |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, v in report["variants"].items():
        lines.append(_row(name, v["summary"]))
    lines += [
        "",
        "Precision@K is bounded by the number of relevant sections (a one-section question caps "
        "P@5 at 0.20), so compare it across variants, not against 1.0. "
        '"Draft in top-k" is the share of ALL questions whose top-k included an unapproved draft '
        'chunk (the draft carries an embedded prompt injection). "Conflict surfaced" is the '
        "share of conflict items whose top-k contained every conflicting section.",
        "",
        "## Recall@5 / MRR by question category",
        "",
    ]
    cats = sorted({c for v in report["variants"].values() for c in v["summary"]["by_category"]})
    lines.append("| Variant | " + " | ".join(cats) + " |")
    lines.append("|---|" + "---|" * len(cats))
    for name, v in report["variants"].items():
        by = v["summary"]["by_category"]
        cells = [
            f"{by[c]['recall@5']:.2f} / {by[c]['mrr']:.2f} (n={by[c]['n']})" if c in by else "-"
            for c in cats
        ]
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    lines += ["", "## Per-item misses (advanced, Recall@5 < 1)", ""]
    adv = report["variants"].get("advanced", {}).get("items", [])
    misses = [r for r in adv if "recall@5" in r and r["recall@5"] < 1]
    if not misses:
        lines.append("None.")
    for r in misses:
        lines.append(
            f"* `{r['id']}` ({r['category']}): R@5 {r['recall@5']:.2f}, top-5 {r['retrieved']}"
        )
    return "\n".join(lines) + "\n"


def write_report(report: dict[str, Any], out_dir: Path = RESULTS_DIR) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    js = out_dir / "retrieval.json"
    md = out_dir / "retrieval.md"
    js.write_text(json.dumps(report, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    md.write_text(render_markdown(report), encoding="utf-8")
    return js, md


ANSWER_ROWS = [
    ("status_accuracy", "Status accuracy (acceptable status)"),
    (
        "insufficient_evidence_accuracy",
        "Insufficient-evidence accuracy (6 out-of-corpus questions)",
    ),
    ("false_insufficient_rate", "False 'insufficient' on answerable questions"),
    ("conflict_review_accuracy", "Unresolved conflict sent to review (C01)"),
    ("injection_resistance", "Prompt-injection resistance (4 adversarial)"),
    ("fabricated_citation_rate", "Fabricated-citation rate (per generated claim)"),
    ("unverified_claim_rate", "Unverified-claim rate (per generated claim)"),
    ("unsupported_answer_rate", "Unsupported-answer rate (answers showing an unverified claim)"),
    ("superseded_citation_rate", "Answers citing a superseded policy version"),
    ("citation_precision", "Citation precision vs expected sections"),
    ("citation_recall", "Citation recall vs expected sections"),
    ("answer_point_coverage", "Expected answer points covered"),
    ("forbidden_point_rate", "Forbidden answer point present"),
]


def _fmt(v: Any) -> str:
    return "-" if v is None else f"{v:.3f}"


def render_answers_markdown(report: dict[str, Any]) -> str:
    from .answer_eval import METRIC_KIND

    prov = report["provenance"]
    levels = list(report["levels"])
    lines = [
        "# UC6 answer evaluation (generated)",
        "",
        "Generated by `dataguard-policy eval answers`. Do not edit by hand.",
        "",
        f"* Run mode: **{prov['mode'].upper()}**; generator `{prov['generator']}`; embeddings "
        f"`{prov['embedding_model_id']}`",
        f"* Golden set: {prov['golden_items']} items, sha256 `{prov['golden_sha256'][:12]}`; corpus "
        f"`{prov['corpus_fingerprint'][:12]}`; config `{prov['config_sha256'][:12]}`; prompt "
        f"`{prov['prompt_version']}`",
    ]
    if prov["mode"] == "offline":
        lines.append(
            "* **OFFLINE: answers come from the extractive stand-in, not a model.** These numbers "
            "exercise the harness only; they are not answer-quality results."
        )
    lines += [
        "* Retrieval quality is reported separately in [`retrieval.md`](retrieval.md).",
        "* Semantic groundedness and answer relevance need a JUDGE (LLM or human) and are **not** "
        "measured here; the deterministic rows are proxies, labelled as such.",
        "",
        "## Naive vs Advanced vs Agentic",
        "",
        "| Metric | Kind | " + " | ".join(levels) + " |",
        "|---|---|" + "---|" * len(levels),
    ]
    for key, label in ANSWER_ROWS:
        cells = [_fmt(report["levels"][lv]["summary"]["metrics"][key]) for lv in levels]
        lines.append(f"| {label} | {METRIC_KIND[key]} | " + " | ".join(cells) + " |")
    agent_levels = [lv for lv in levels if report["levels"][lv]["summary"].get("agent")]
    if agent_levels:
        from .answer_eval import AGENT_METRIC_KIND

        lines += ["", "## Agent behaviour (Agentic RAG)", "", "| Metric | Kind | " + " | ".join(agent_levels) + " |",
                  "|---|---|" + "---|" * len(agent_levels)]  # fmt: skip
        for key, kind in AGENT_METRIC_KIND.items():
            cells = [_fmt(report["levels"][lv]["summary"]["agent"][key]) for lv in agent_levels]
            lines.append(f"| {key.replace('_', ' ')} | {kind} | " + " | ".join(cells) + " |")
        for lv in agent_levels:
            ag = report["levels"][lv]["summary"]["agent"]
            lines.append("")
            lines.append(
                f"* {lv}: stop reasons {ag['stopped_reasons']}; tool usage {ag['tool_usage']}"
            )
    lines += ["", "## Status counts", "", "| Level | Statuses | Generation errors | Claims generated |",
              "|---|---|---|---|"]  # fmt: skip
    for lv in levels:
        s = report["levels"][lv]["summary"]
        counts = ", ".join(f"{k} {v}" for k, v in s["status_counts"].items())
        lines.append(f"| {lv} | {counts} | {s['llm_errors']} | {s['counts']['claims_generated']} |")
    lines += ["", "## Per-item outcomes", "", "| Item | Category | " + " | ".join(levels) + " |",
              "|---|---|" + "---|" * len(levels)]  # fmt: skip
    by_level = {lv: {r["id"]: r for r in report["levels"][lv]["items"]} for lv in levels}
    for item_id in [r["id"] for r in report["levels"][levels[0]]["items"]]:
        cat = by_level[levels[0]][item_id]["category"]
        cells = []
        for lv in levels:
            r = by_level[lv][item_id]
            mark = "ok" if r["status_ok"] and not r["forbidden_hit"] else "**MISS**"
            extra = []
            if r["shown_unverified"]:
                extra.append(f"{r['shown_unverified']} unverified shown")
            if r["fabricated_citations"]:
                extra.append(f"{r['fabricated_citations']} fabricated")
            if r["superseded_cited"]:
                extra.append("cites superseded")
            if r["forbidden_hit"]:
                extra.append("forbidden phrase")
            cells.append(f"{r['status']} ({mark}{'; ' + ', '.join(extra) if extra else ''})")
        lines.append(f"| {item_id} | {cat} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def write_answers_report(report: dict[str, Any], out_dir: Path = RESULTS_DIR) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    # One file pair per prompt version, so an earlier prompt's results are never overwritten.
    stem = f"answers.{report['provenance']['prompt_version']}"
    js = out_dir / f"{stem}.json"
    md = out_dir / f"{stem}.md"
    js.write_text(json.dumps(report, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    md.write_text(render_answers_markdown(report), encoding="utf-8")
    return js, md
